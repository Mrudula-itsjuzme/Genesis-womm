"""Export Core's contracts from code (spine AD-18).

    uv run python -m scripts.export_contracts           # write the files
    uv run python -m scripts.export_contracts --check   # exit 1 if they drifted

Writes ``contracts/core-api.openapi.yaml`` and ``contracts/schemas/shared.schema.json``.
The shared schema holds the cross-service shapes (error envelope, conflict, agent action,
citation) so that Agent and Web can validate producer output and their own fakes against them.
"""

import json
import sys
from pathlib import Path
from typing import Any

import yaml
from pydantic import SecretStr

from app.container import Container
from app.main import create_app
from app.services.readiness import ReadinessService
from app.settings import Settings

REPO_ROOT = Path(__file__).resolve().parents[3]
CONTRACTS = REPO_ROOT / "contracts"
OPENAPI_PATH = CONTRACTS / "core-api.openapi.yaml"
SHARED_PATH = CONTRACTS / "schemas" / "shared.schema.json"

SHARED_ROOTS = ("ErrorEnvelope", "Conflict", "AgentAction", "Citation")
GENERATED_NOTE = "Generated by services/core-api/scripts/export_contracts.py. Do not edit by hand."

_REF_PREFIX = "#/components/schemas/"


class _NoProbe:
    def database_reachable(self) -> bool:
        return False

    def applied_migration(self) -> str | None:
        return None


def build_openapi() -> dict[str, Any]:
    # Placeholder values only: exporting a contract never needs real configuration.
    settings = Settings(
        _env_file=None,
        session_signing_key=SecretStr("export-only-session-key-0000000000000"),
        delegation_signing_key=SecretStr("export-only-delegation-key-00000000000"),
    )
    container = Container(readiness=ReadinessService(_NoProbe(), expected_head="export"))
    document: dict[str, Any] = create_app(settings, container).openapi()
    return document


def _rewrite_refs(node: Any) -> Any:
    if isinstance(node, dict):
        return {
            key: (
                "#/$defs/" + value.removeprefix(_REF_PREFIX)
                if key == "$ref" and isinstance(value, str)
                else _rewrite_refs(value)
            )
            for key, value in node.items()
        }
    if isinstance(node, list):
        return [_rewrite_refs(item) for item in node]
    return node


def _referenced(node: Any) -> set[str]:
    found: set[str] = set()
    if isinstance(node, dict):
        for key, value in node.items():
            if key == "$ref" and isinstance(value, str) and value.startswith(_REF_PREFIX):
                found.add(value.removeprefix(_REF_PREFIX))
            else:
                found |= _referenced(value)
    elif isinstance(node, list):
        for item in node:
            found |= _referenced(item)
    return found


def build_shared_schema(openapi: dict[str, Any]) -> dict[str, Any]:
    components: dict[str, Any] = openapi["components"]["schemas"]
    wanted: set[str] = set()
    pending = list(SHARED_ROOTS)
    while pending:
        name = pending.pop()
        if name in wanted:
            continue
        wanted.add(name)
        pending.extend(_referenced(components[name]))
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "CampusCue shared cross-service schemas",
        "description": GENERATED_NOTE,
        "$defs": {name: _rewrite_refs(components[name]) for name in sorted(wanted)},
    }


def render_all() -> dict[Path, str]:
    openapi = build_openapi()
    yaml_text = yaml.safe_dump(openapi, sort_keys=False, allow_unicode=True, width=100)
    shared_text = json.dumps(build_shared_schema(openapi), indent=2, ensure_ascii=False) + "\n"
    return {
        OPENAPI_PATH: f"# {GENERATED_NOTE}\n{yaml_text}",
        SHARED_PATH: shared_text,
    }


def find_drift() -> list[str]:
    drifted = []
    for path, expected in render_all().items():
        if not path.exists() or path.read_text() != expected:
            drifted.append(str(path.relative_to(REPO_ROOT)))
    return drifted


def write_all() -> None:
    for path, text in render_all().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path.relative_to(REPO_ROOT)}")


def main(argv: list[str]) -> int:
    if "--check" in argv:
        drift = find_drift()
        if drift:
            print("contracts are out of date:", *drift, sep="\n  ")
            print("run: uv run python -m scripts.export_contracts")
            return 1
        print("contracts are up to date")
        return 0
    write_all()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
