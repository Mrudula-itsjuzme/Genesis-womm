"""Export the Agent's OpenAPI from code (spine AD-18).

    uv run python -m scripts.export_contracts           # write the file
    uv run python -m scripts.export_contracts --check   # exit 1 if it drifted

Writes ``contracts/agent-api.openapi.yaml``. The shared cross-service schemas are produced by
Core; the Agent's contract tests compare against them instead of re-exporting them.
"""

import sys
from pathlib import Path
from typing import Any

import yaml

from app.container import Container
from app.main import create_app
from app.orchestration.readiness import ReadinessService
from app.settings import Settings

REPO_ROOT = Path(__file__).resolve().parents[3]
CONTRACTS = REPO_ROOT / "contracts"
OPENAPI_PATH = CONTRACTS / "agent-api.openapi.yaml"
GENERATED_NOTE = "Generated by services/agent-api/scripts/export_contracts.py. Do not edit by hand."


def build_openapi() -> dict[str, Any]:
    # Defaults only: exporting a contract never needs real configuration or credentials.
    settings = Settings(_env_file=None)
    container = Container(readiness=ReadinessService(provider="fake", has_credential=False))
    document: dict[str, Any] = create_app(settings, container).openapi()
    return document


def render_all() -> dict[Path, str]:
    yaml_text = yaml.safe_dump(build_openapi(), sort_keys=False, allow_unicode=True, width=100)
    return {OPENAPI_PATH: f"# {GENERATED_NOTE}\n{yaml_text}"}


def find_drift() -> list[str]:
    drifted = []
    for path, expected in render_all().items():
        if not path.exists() or path.read_text() != expected:
            drifted.append(str(path.relative_to(REPO_ROOT)))
    return drifted


def write_all() -> None:
    for path, text in render_all().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path.relative_to(REPO_ROOT)}")


def main(argv: list[str]) -> int:
    if "--check" in argv:
        drift = find_drift()
        if drift:
            print("contracts are out of date:", *drift, sep="\n  ")
            print("run: uv run python -m scripts.export_contracts")
            return 1
        print("contracts are up to date")
        return 0
    write_all()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
